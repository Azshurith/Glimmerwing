import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const out = await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  loader: { '.png': 'dataurl', '.jpg': 'dataurl' },
  // GW_SERVER=wss://your-host/ws npm run build  bakes in where the online relay lives.
  define: { __GW_SERVER__: JSON.stringify(process.env.GW_SERVER ?? '') },
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
mkdirSync('dist', { recursive: true });
const html = readFileSync('index.template.html', 'utf8').replace('/*__BUNDLE__*/', () => js);
writeFileSync('dist/index.html', html);

// Installable web app: a manifest, icons, and a service worker so it opens offline.
// Everything is relative, so the folder works at any path (your server, itch.io, GitHub Pages).
for (const n of [192, 512]) copyFileSync(`assets/icon-${n}.png`, `dist/icon-${n}.png`);
writeFileSync(
  'dist/manifest.webmanifest',
  JSON.stringify(
    {
      name: 'Glimmerwing',
      short_name: 'Glimmerwing',
      description:
        "A split-screen versus shooter: chain dandelion bursts in your meadow to send stars into your rival's.",
      start_url: './',
      scope: './',
      display: 'fullscreen',
      display_override: ['fullscreen', 'standalone'],
      orientation: 'landscape',
      background_color: '#100b24',
      theme_color: '#100b24',
      categories: ['games'],
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  ),
);
// The cache name changes with every build, so players get new versions on their next visit.
const version = createHash('sha256').update(html).digest('hex').slice(0, 12);
writeFileSync(
  'dist/sw.js',
  `// Glimmerwing offline cache (generated by build.mjs).
const CACHE = 'glimmerwing-${version}';
const FILES = ['./', 'index.html', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png'];
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
// The game page: network first (so updates arrive), the cached copy when offline.
// Fonts and everything else: cache first, filled as they're fetched.
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || req.url.includes('/ws')) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); return res; })
      .catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
    if (res.ok && (req.url.startsWith(self.location.origin) || req.url.includes('fonts.g'))) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  })));
});
`,
);
console.log('built dist/index.html', js.length, 'bytes of JS; app manifest, icons and service worker', version);
